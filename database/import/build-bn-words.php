$source = $argv[1] ?? '';
if (!is_file($source)) {
    fwrite(STDERR, "word.xml-এর পথ দিন\n");
    exit(1);
}

// সচরাচর ব্যবহৃত শব্দ — সাজেশনে সবার আগে আসে
$common = preg_split('/\s+/u', trim('আমি আমার আমাকে আমাদের আমরা আপনি আপনার আপনাকে আপনাদের তুমি তোমার তোমাকে তোমাদের সে তার তাকে তাদের এই এটা এটি এখন এখানে এবং এবার এছাড়া ওই ওটা তাই তাহলে তবে কিন্তু যদি যেহেতু কারণ আর আরও অন্য অনেক কিছু কিছুই কেউ কোনো কোথায় কখন কেন কীভাবে কত কী কি না হ্যাঁ জি ধন্যবাদ অনুগ্রহ করে করুন করা করি করব করবেন করতে করছি করেছি করেছেন করছেন হবে হয় হয়েছে হচ্ছে হতে চাই চাইছি চান চাইলে বলতে বলুন বলেন দিন দিয়ে দেওয়া দিতে নিন নিয়ে নেওয়া পাবেন পারি পারেন পারবেন পারব যাবে যান যাচ্ছি আছে আছেন আছি থাকে থাকবে ছিল আসুন আসবেন এসেছি দেখুন দেখতে জানতে জানাতে জানান জানাই লিখুন কাজ কাজের কাজে কাজটি সেবা সেবার সেবাটি কর্মী পেশা পেশাজীবী অভিজ্ঞতা বছর মাস দিন সময় সকাল দুপুর বিকাল সন্ধ্যা রাত আজ আজকে আগামী কাল গতকাল সপ্তাহ টাকা মূল্য খরচ ভাড়া মোবাইল ফোন নম্বর নাম্বার ঠিকানা এলাকা বাড়ি বাসা রোড সড়ক গলি বাজার মসজিদ স্কুল কলেজ হাসপাতাল অফিস দোকান ঢাকা চট্টগ্রাম সিলেট রাজশাহী খুলনা বরিশাল রংপুর ময়মনসিংহ বিভাগ জেলা উপজেলা থানা গ্রাম শহর বাংলাদেশ সমস্যা সমাধান যোগাযোগ সাহায্য সহযোগিতা প্রয়োজন দরকার জরুরি তাড়াতাড়ি দ্রুত ভালো খুব সুন্দর ঠিক সঠিক সহজ কঠিন নতুন পুরনো বড় ছোট বেশি কম সব সবাই সবার একটা একটি দুটি তিনটি চারটি পাঁচটি প্রথম দ্বিতীয় শেষ জন্য সঙ্গে সাথে থেকে পর্যন্ত মধ্যে ভিতরে বাইরে উপর নিচে আগে পরে এর ওর তোর কাছে কাছাকাছি দূরে স্যার ম্যাডাম ভাই আপু বোন ভাইয়া মামা চাচা বাবা মা সন্তান পরিবার'), -1, PREG_SPLIT_NO_EMPTY);

// সাইটের নিজের শব্দ: সেবার নাম ও এলাকার নাম (বাংলা অংশ) থেকে
$site = [];
foreach (['services.php', 'geo.php'] as $file) {
    $text = (string) file_get_contents(__DIR__ . '/../seeds/' . $file);
    preg_match_all('/[\x{0980}-\x{09FF}]+/u', $text, $m);
    foreach ($m[0] as $word) {
        $site[$word] = ($site[$word] ?? 0) + 1;
    }
}
arsort($site);

preg_match_all('/<([^\/>\s]+)>[a-zA-Z_]*<\/\1>/u', (string) file_get_contents($source), $m);
$archaic = '/(ইয়া|ইতে|ইতা|ইবে|ইবা|ইল[ুা]ম|ইলি|ইস|িয়ে?ছ|চ্ছিল)/u';
$rest = [];
foreach (array_unique($m[1]) as $word) {
    if (mb_strlen($word) >= 2 && !preg_match($archaic, $word)) {
        $rest[$word] = true;
    }
}

$first = [];
foreach (array_merge($common, array_keys($site)) as $word) {
    if (mb_strlen($word) >= 2) {
        $first[$word] = true;
    }
}
$rest = array_diff_key($rest, $first);
$names = array_keys($rest);
sort($names);

$out = __DIR__ . '/../../public/assets/vendor/bnwords/bn-words-v1.txt';
file_put_contents($out, implode("\n", array_keys($first)) . "\n\n" . implode("\n", $names));
echo count($first), ' আগের শব্দ, ', count($names), " বাকি শব্দ\n";
