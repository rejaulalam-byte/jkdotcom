/** বাংলা অঙ্ক (এই স্ক্রিপ্টের নিজের ছোট সহায়ক) */
function bn_digits(int $n): string
{
    return strtr((string) $n, ['0' => '০', '1' => '১', '2' => '২', '3' => '৩', '4' => '৪', '5' => '৫', '6' => '৬', '7' => '৭', '8' => '৮', '9' => '৯']);
}

